import { FACTORY_REPO } from "../constants.js";
import { RUNNER_PATH, shellQuote } from "./cli.js";
import { GIT_BINARY, rewriteGuard } from "./git-cli.js";
import { REMOTE_URL, REPO_DIR } from "./git-remote.js";

/**
 * The signed push: the implementer's branch delivered as commits GitHub
 * signs.
 *
 * @remarks
 * A commit made in a sandbox is unsigned, and a ruleset that requires
 * signed commits on the factory's branches rejects it. GitHub signs a
 * commit a GitHub App creates through the Git Data API, so with
 * {@link SIGNED_COMMITS_ENV} set the runtime runs
 * {@link PUSH_SIGNED_SCRIPT} in the sandbox in place of `git push`. The
 * script recreates each commit GitHub lacks (blobs, tree, commit), moves
 * the branch ref, then moves the local branch onto the signed commits:
 * same trees, so the working tree is untouched and only the SHAs change.
 *
 * What stays as it is for a plain push:
 *
 * - The runtime decides what is pushed. The branch passed
 *   `validateBranch`, the repository is `FACTORY_REPO`, and the fetch URL
 *   is the literal one. The script takes all three from its environment
 *   and reads nothing about the remote from git config, which the model
 *   can write.
 * - It never forces: the ref is created, or moved with `force: false`, so
 *   GitHub refuses anything but a fast-forward.
 * - It runs under a `repo-push` lease, hooks off, HTTPS only, behind the
 *   URL-rewrite guard, within the same time limit.
 *
 * What differs: the lease also covers `api.github.com`. What a run taken
 * over by its input can reach is unchanged (the `repo-push` token: contents
 * on the factory repository), since a plain push runs in the implementer's
 * sandbox too.
 *
 * Off by default: a plain push is one request, not several per commit, and
 * a signed push cannot carry Git LFS files (the script refuses them).
 */

/** Set to `1` to deliver branches as commits GitHub signs. */
export const SIGNED_COMMITS_ENV = "FACTORY_SIGNED_COMMITS";

/** Whether pushes are signed, read when a push runs. */
export const signedCommits = (): boolean =>
  process.env[SIGNED_COMMITS_ENV]?.trim() === "1";

/**
 * How long a replay may take: the same limit as a plain push.
 *
 * @remarks
 * A replay makes several requests per commit, but it gets no longer than
 * any other git command the runtime runs inside a tool call: the lease is
 * taken off in a `finally`, and a tool call the platform ended first would
 * never reach it, leaving the push credential attached. The script uploads
 * blobs several at a time to fit. A branch too large to replay in this time
 * fails before its ref moves, and the push can be run again, since GitHub
 * keeps the objects already sent.
 */
export const SIGNED_PUSH_TIMEOUT_MS = 110_000;

/** The names the script reads its instructions from. */
export const PUSH_VARIABLES = {
  api: "FACTORY_PUSH_API",
  branch: "FACTORY_PUSH_BRANCH",
  credential: "FACTORY_PUSH_CREDENTIAL",
  directory: "FACTORY_PUSH_DIR",
  git: "FACTORY_PUSH_GIT",
  gitPath: "FACTORY_PUSH_GIT_PATH",
  remote: "FACTORY_PUSH_REMOTE",
  repository: "FACTORY_PUSH_REPO",
} as const;

/**
 * What the script is told, for one push.
 *
 * @param branch - A branch name that passed `validateBranch`.
 * @param placeholder - The lease's placeholder, which the sandbox firewall
 * swaps for the token on the way out.
 */
export const signedPushEnvironment = (
  branch: string,
  placeholder: string
): Record<string, string> => ({
  [PUSH_VARIABLES.branch]: branch,
  [PUSH_VARIABLES.credential]: placeholder,
  [PUSH_VARIABLES.directory]: REPO_DIR,
  [PUSH_VARIABLES.git]: GIT_BINARY,
  [PUSH_VARIABLES.gitPath]: RUNNER_PATH,
  [PUSH_VARIABLES.remote]: REMOTE_URL,
  [PUSH_VARIABLES.repository]: FACTORY_REPO,
});

/**
 * The command that runs the script and removes it again.
 *
 * @param scriptPath - Where the runtime wrote {@link PUSH_SIGNED_SCRIPT}.
 */
export const signedPushCommandLine = (scriptPath: string): string => {
  const script = shellQuote(scriptPath);
  return `${rewriteGuard(REPO_DIR)}; node ${script}; status=$?; rm -f ${script}; exit $status`;
};

/**
 * The script, as CommonJS for the sandbox's Node.js.
 *
 * @remarks
 * Plain JavaScript in a string, because it runs in the sandbox, not in the
 * app runtime. It holds no backtick and no template placeholder, so the
 * text here is the text that runs. `tests/github/push-signed.test.ts` runs
 * it with the real git against a local bare repository and a stand-in for
 * the Git Data API.
 */
export const PUSH_SIGNED_SCRIPT = String.raw`#!/usr/bin/env node
// Software factory signed push. Generated by agent/lib/github/push-signed.ts;
// edit that file, not this one. Recreates the branch's new commits through
// GitHub's Git Data API so GitHub signs them, then moves the branch ref.
"use strict";
const { execFileSync, spawnSync } = require("node:child_process");
const { existsSync, readFileSync } = require("node:fs");

const fail = (message) => {
  console.error("error: " + message);
  process.exit(1);
};
const need = (name) => process.env[name] || fail(name + " is not set");

const GIT = need("FACTORY_PUSH_GIT");
const DIR = need("FACTORY_PUSH_DIR");
const REPO = need("FACTORY_PUSH_REPO");
const BRANCH = need("FACTORY_PUSH_BRANCH");
const REMOTE = need("FACTORY_PUSH_REMOTE");
const CREDENTIAL = need("FACTORY_PUSH_CREDENTIAL");
const API = process.env.FACTORY_PUSH_API || "https://api.github.com";
const RETRIES = 4;
// Blobs sent at once. Enough to fit a large change in the time a push gets.
const UPLOADS = 8;

// The runtime validated these already; a second look costs nothing.
if (!/^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+$/.test(REPO)) fail("not a repository: " + REPO);
if (!/^[A-Za-z0-9][A-Za-z0-9._\/-]*$/.test(BRANCH) || BRANCH.includes("..")) {
  fail("not a branch name: " + BRANCH);
}

// git's own lookups stay in the image's directories.
const gitEnv = { ...process.env };
if (process.env.FACTORY_PUSH_GIT_PATH) gitEnv.PATH = process.env.FACTORY_PUSH_GIT_PATH;
const gitRaw = (args, options) =>
  execFileSync(GIT, ["-C", DIR, ...args], {
    env: gitEnv,
    maxBuffer: Number.POSITIVE_INFINITY,
    stdio: ["ignore", "pipe", "pipe"],
    ...options,
  });
const git = (...args) => gitRaw(args).toString().trim();
const gitOk = (...args) =>
  spawnSync(GIT, ["-C", DIR, ...args], { env: gitEnv, stdio: "ignore" }).status === 0;

const LOCAL_REF = "refs/heads/" + BRANCH;
const TRACKING = "refs/remotes/origin/" + BRANCH;
const ENCODED = BRANCH.split("/").map(encodeURIComponent).join("/");

// --- GitHub API ------------------------------------------------------------
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// Resolves to { status, payload }. Retries rate limits and server errors;
// any other status outside "accept" ends the push with GitHub's message.
async function api(method, path, body, accept) {
  for (let attempt = 0; ; attempt += 1) {
    let response;
    try {
      response = await fetch(API + "/repos/" + REPO + path, {
        body: body === undefined ? undefined : JSON.stringify(body),
        headers: {
          accept: "application/vnd.github+json",
          authorization: "Bearer " + CREDENTIAL,
          "content-type": "application/json",
          "x-github-api-version": "2022-11-28",
        },
        method,
      });
    } catch (error) {
      if (attempt < RETRIES) {
        await sleep(2 ** attempt * 500);
        continue;
      }
      fail(method + " " + path + " could not reach GitHub: " + error.message);
    }
    const text = await response.text();
    let payload = {};
    try {
      payload = text ? JSON.parse(text) : {};
    } catch {
      payload = { message: text.slice(0, 200) };
    }
    if (response.ok || (accept || []).includes(response.status)) {
      return { payload, status: response.status };
    }
    const limited =
      response.status === 429 ||
      (response.status === 403 && /rate limit/i.test(payload.message || ""));
    if ((limited || response.status >= 500) && attempt < RETRIES) {
      const retryAfter = Number(response.headers.get("retry-after"));
      await sleep(retryAfter > 0 ? retryAfter * 1000 : 2 ** attempt * 1000);
      continue;
    }
    fail(method + " " + path + " failed: " + response.status + " " + (payload.message || ""));
  }
}

const fetchBranch = () =>
  gitOk("fetch", "--quiet", REMOTE, "+" + LOCAL_REF + ":" + TRACKING);

// --- What to send ----------------------------------------------------------
// Changed paths between the first parent and the commit, with modes. A
// commit with no parent lists its whole tree.
function changedEntries(parent, commit) {
  const entries = [];
  if (!parent) {
    const lines = git("ls-tree", "-r", "-z", "--full-tree", commit).split("\0");
    for (const line of lines.filter(Boolean)) {
      const tab = line.indexOf("\t");
      const [mode, type, sha] = line.slice(0, tab).split(" ");
      entries.push({ mode, path: line.slice(tab + 1), sha, type });
    }
    return entries;
  }
  const fields = git("diff-tree", "-r", "-z", "--no-renames", "--raw", parent, commit)
    .split("\0")
    .filter(Boolean);
  for (let i = 0; i < fields.length; i += 2) {
    const [, newMode, , newSha, status] = fields[i].replace(/^:/, "").split(" ");
    const path = fields[i + 1];
    if (status === "D") {
      entries.push({ mode: "100644", path, sha: null, type: "blob" });
    } else {
      entries.push({ mode: newMode, path, sha: newSha, type: newMode === "160000" ? "commit" : "blob" });
    }
  }
  return entries;
}

// The Git Data API cannot upload LFS objects, so an added or changed
// LFS-tracked path would land as a pointer to an object GitHub does not
// have. Attributes are read from the commit itself where git supports it.
function refuseLfs(commit, entries) {
  const paths = entries.filter((e) => e.type === "blob" && e.sha !== null).map((e) => e.path);
  if (paths.length === 0) return;
  const input = paths.join("\0") + "\0";
  let out;
  try {
    out = gitRaw(["check-attr", "-z", "--stdin", "--source", commit, "filter"], {
      input,
      stdio: ["pipe", "pipe", "pipe"],
    });
  } catch {
    // An older git has no --source; the working tree's rules are the next best.
    out = gitRaw(["check-attr", "-z", "--stdin", "filter"], {
      input,
      stdio: ["pipe", "pipe", "pipe"],
    });
  }
  const fields = out.toString().split("\0");
  const lfs = [];
  for (let i = 0; i + 2 < fields.length; i += 3) {
    if (fields[i + 2] === "lfs") lfs.push(fields[i]);
  }
  if (lfs.length > 0) {
    fail(
      commit.slice(0, 7) + " adds or changes Git LFS files, which a signed push cannot carry: " +
        lfs.slice(0, 5).join(", ") + (lfs.length > 5 ? ", ..." : "")
    );
  }
}

async function uploadBlob(entry) {
  const { payload } = await api("POST", "/git/blobs", {
    content: gitRaw(["cat-file", "blob", entry.sha]).toString("base64"),
    encoding: "base64",
  });
  if (payload.sha !== entry.sha) fail("blob mismatch for " + entry.path);
}

async function uploadAll(blobs) {
  for (let i = 0; i < blobs.length; i += UPLOADS) {
    await Promise.all(blobs.slice(i, i + UPLOADS).map(uploadBlob));
  }
}

// Creates the commit's tree on GitHub and checks it is the same tree.
async function createTree(commit, parent, entries, newObjects) {
  const tree = git("rev-parse", commit + "^{tree}");
  // A commit that changes no files has its parent's tree, which GitHub has.
  if (entries.length === 0) return tree;
  const blobs = entries.filter((e) => e.type === "blob" && e.sha !== null);
  await uploadAll(blobs.filter((entry) => newObjects.has(entry.sha)));
  const body = {
    base_tree: parent ? git("rev-parse", parent + "^{tree}") : undefined,
    tree: entries.map(({ mode, path, sha, type }) => ({ mode, path, sha, type })),
  };
  let created = await api("POST", "/git/trees", body, [422]);
  if (created.status === 422) {
    // GitHub lacks a blob the checkout believed it had. Send them all once.
    await uploadAll(blobs.filter((entry) => !newObjects.has(entry.sha)));
    created = await api("POST", "/git/trees", body);
  }
  if (created.payload.sha !== tree) fail("tree mismatch for " + commit.slice(0, 7));
  return tree;
}

// The commit's message ending in exactly one newline, as git commit writes it.
const messageOf = (commit) =>
  gitRaw(["log", "-1", "--format=%B", commit]).toString().replace(/\s+$/, "") + "\n";

async function main() {
  if (!gitOk("rev-parse", "--verify", "--quiet", LOCAL_REF + "^{commit}")) {
    fail("there is no local branch " + BRANCH + "; commit your work to it, then push");
  }
  const local = git("rev-parse", LOCAL_REF);

  // Ask GitHub where the branch is, not the checkout's remote-tracking ref.
  const ref = await api("GET", "/git/ref/heads/" + ENCODED, undefined, [404]);
  const remoteHead = ref.status === 404 ? null : ref.payload.object.sha;

  if (remoteHead === local) {
    fetchBranch();
    console.log("Everything up-to-date");
    return;
  }
  if (remoteHead) {
    if (!fetchBranch()) fail("could not fetch " + BRANCH + " from GitHub to compare it with yours");
    if (!gitOk("merge-base", "--is-ancestor", remoteHead, local)) {
      fail(
        "updates were rejected: " + BRANCH + " on GitHub has commits yours does not (non-fast-forward). " +
          "Run git pull --rebase origin " + BRANCH + ", then push again."
      );
    }
  }

  // Commits the checkout believes GitHub lacks, parents before children.
  const exclude = ["--not", "--remotes=origin"].concat(remoteHead ? [remoteHead] : []);
  const candidates = git("rev-list", "--reverse", "--topo-order", "--parents", local, ...exclude)
    .split("\n")
    .filter(Boolean)
    .map((line) => line.split(" "));
  const newObjects = new Set(
    git("rev-list", "--objects", "--no-object-names", local, ...exclude).split("\n")
  );
  const shallowFile = git("rev-parse", "--git-path", "shallow");
  const shallowPath = shallowFile.startsWith("/") ? shallowFile : DIR + "/" + shallowFile;
  const shallow = existsSync(shallowPath) ? readFileSync(shallowPath, "utf8") : "";

  const replayed = new Map(); // local sha -> signed sha
  for (const [commit, ...parents] of candidates) {
    // The remote-tracking refs are the checkout's own account of what GitHub
    // has, and can be stale. A commit none of whose parents was recreated
    // might be on GitHub already; ask before recreating it under a new SHA.
    if (!parents.some((parent) => replayed.has(parent))) {
      const known = await api("GET", "/git/commits/" + commit, undefined, [404, 409, 422]);
      if (known.status === 200) continue;
    }
    if (parents.length === 0 && shallow.includes(commit)) {
      fail("this checkout is shallow and GitHub lacks its oldest commit; run git fetch --unshallow origin, then push again");
    }
    const entries = changedEntries(parents[0], commit);
    refuseLfs(commit, entries);
    const tree = await createTree(commit, parents[0], entries, newObjects);
    // No author or committer: GitHub signs only the commits it attributes to the app itself.
    const signed = await api("POST", "/git/commits", {
      message: messageOf(commit),
      parents: parents.map((parent) => replayed.get(parent) || parent),
      tree,
    });
    replayed.set(commit, signed.payload.sha);
  }

  // Never forced: GitHub refuses anything but a fast-forward.
  const head = replayed.get(local) || local;
  if (remoteHead) {
    await api("PATCH", "/git/refs/heads/" + ENCODED, { force: false, sha: head });
  } else {
    await api("POST", "/git/refs", { ref: LOCAL_REF, sha: head });
  }

  // Same trees, new commits: move the local branch without touching files.
  if (!fetchBranch()) {
    fail(
      BRANCH + " was pushed, but the signed commits could not be fetched back. " +
        "Run git fetch origin " + BRANCH + " && git reset --soft origin/" + BRANCH + " before committing again."
    );
  }
  // Moving the ref alone leaves the index and the files as they are, whether
  // or not the branch is the one checked out.
  if (head !== local) git("update-ref", LOCAL_REF, head, local);

  const count = replayed.size + " signed commit" + (replayed.size === 1 ? "" : "s");
  console.log("To " + REMOTE);
  console.log(
    (remoteHead ? "   " + remoteHead.slice(0, 7) + ".." + head.slice(0, 7) : " * [new branch]") +
      "  " + BRANCH + " -> " + BRANCH + " (" + count + ")"
  );
  if (replayed.size > 0) {
    console.log("GitHub signed the new commits, so their SHAs changed. " + BRANCH + " now points at " + head.slice(0, 7) + "; the files are unchanged.");
  }
}

main().catch((error) => fail(error.message));
`;
