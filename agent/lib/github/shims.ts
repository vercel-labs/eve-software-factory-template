import { GH_BINARY, GH_COMMANDS, GH_WRITE_COMMANDS } from "./cli.js";
import { GIT_BINARY } from "./git-cli.js";

/**
 * The `gh` and `git` wrappers seeded into every factory sandbox.
 *
 * @remarks
 * Agents run `git` and `gh` in their shell as usual. The names resolve to
 * these scripts, installed ahead of the real binaries on `PATH`
 * (`agent/lib/github/tooling.ts`), and each script ends by running the real
 * program with the caller's own arguments.
 *
 * What a wrapper does:
 *
 * - Attaches the command's credential. The `bash` tool exports a one-off
 *   placeholder (`FACTORY_GITHUB_LEASE`) for the commands that name `gh` or
 *   `git`; the wrapper hands it to the real program, and the sandbox
 *   firewall swaps it for a token on the way out. No token is ever in the
 *   sandbox.
 * - Pins `gh` to the factory repository and turns its prompts off.
 * - Keeps `gh` to the factory's command list, and sends a command that
 *   would change GitHub back with the words that will work, since only a
 *   command the `bash` tool can read in full gets a credential that writes.
 *
 * What a wrapper is not: a security boundary. It is a file in a sandbox
 * where the agent has a shell, so anything it refuses, the real binary would
 * still try. The boundary is the credential: a shell command only ever gets
 * a read-only token, and the tokens that write are leased to commands the
 * app runtime parsed and approved itself (`agent/lib/github/tools.ts`).
 *
 * The scripts are plain POSIX `sh` and take the real binary's path as their
 * only build-time input, so the test suite can run them against stand-ins.
 */

/** Environment variables the `bash` tool sets for a command under a lease. */
export const LEASE_VARIABLE = "FACTORY_GITHUB_LEASE";
export const REPO_VARIABLE = "FACTORY_REPO";
export const ROLE_VARIABLE = "FACTORY_GITHUB_ROLE";

/** Who is running the command, which decides how a refusal is worded. */
export type ShellRole = "implementer" | "orchestrator" | "reader";

const NO_CREDENTIAL =
  "no GitHub credential is attached to this command. One is attached only when the bash command itself names gh or git, so run it directly in your bash command, not from inside a script.";

/*
 * The hints are echoed from inside double quotes in a shell script, so they
 * must not contain a quote, a dollar sign, a backtick, or a backslash
 * (`tests/github/shims.test.ts` holds them to that).
 */
export const GH_WRITE_HINT =
  "changes GitHub, so it has to be the whole bash command: only gh commands (several joined with &&), every argument written out, no pipes, variables, or redirects. For text with several lines, pass --body with a quoted heredoc, or write the text to a file and pass --body-file.";

export const GH_READER_HINT =
  "changes GitHub, and this agent only reads it. Report what should change in your structured output.";

export const PUSH_HINT =
  "git push has to be the whole bash command, written as: git push origin <branch>.";

export const NO_PUSH_HINT =
  "this agent reads the repository and never pushes. Report what should change in your structured output.";

const caseList = (entries: readonly string[]): string =>
  entries.map((entry) => `'${entry}'`).join("|");

/** The `gh` wrapper script. */
export const ghShim = (real: string = GH_BINARY): string => `#!/bin/sh
# Software factory wrapper for the GitHub CLI. Generated by
# agent/lib/github/shims.ts; edit that file, not this one.
real='${real}'

for argument in "$@"; do
  case "$argument" in
    --help|--version) exec "$real" "$@" ;;
  esac
done
case "\${1:-}" in
  ''|help|version|-h) exec "$real" "$@" ;;
esac

if [ "$1" = api ]; then
  path=api
else
  path="$1 \${2:-}"
fi
case "$path" in
  ${caseList(GH_COMMANDS)}) ;;
  *)
    echo "gh $path is not available to the factory. Available: ${GH_COMMANDS.join(", ")}." >&2
    exit 2
    ;;
esac

if [ -z "\${${LEASE_VARIABLE}:-}" ] || [ -z "\${${REPO_VARIABLE}:-}" ]; then
  echo "gh: ${NO_CREDENTIAL}" >&2
  exit 4
fi

case "$path" in
  ${caseList(GH_WRITE_COMMANDS)})
    if [ "\${${ROLE_VARIABLE}:-}" = orchestrator ]; then
      echo "gh $path ${GH_WRITE_HINT}" >&2
    else
      echo "gh $path ${GH_READER_HINT}" >&2
    fi
    exit 2
    ;;
esac

normalize() {
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -e 's#^https://##' -e 's#^github\\.com/##' -e 's#\\.git$##'
}
factory=$(normalize "$${REPO_VARIABLE}")
previous=''
for argument in "$@"; do
  other=''
  case "$previous" in
    -R|--repo) other="$argument" ;;
  esac
  case "$argument" in
    --repo=*) other="\${argument#--repo=}" ;;
  esac
  if [ -n "$other" ] && [ "$(normalize "$other")" != "$factory" ]; then
    echo "gh works on $${REPO_VARIABLE} only; leave out --repo." >&2
    exit 2
  fi
  previous="$argument"
done

GH_TOKEN="$${LEASE_VARIABLE}" GH_REPO="$${REPO_VARIABLE}" GH_PROMPT_DISABLED=1 GH_NO_UPDATE_NOTIFIER=1 exec "$real" "$@"
`;

/** The `git` wrapper script. */
export const gitShim = (real: string = GIT_BINARY): string => `#!/bin/sh
# Software factory wrapper for git. Generated by agent/lib/github/shims.ts;
# edit that file, not this one. Everything that stays on this machine goes
# straight to git; only the commands that talk to a remote are touched.
real='${real}'

subcommand=''
skip=0
for argument in "$@"; do
  if [ "$skip" = 1 ]; then
    skip=0
    continue
  fi
  case "$argument" in
    -C|-c|--git-dir|--work-tree|--namespace|--config-env) skip=1 ;;
    -*) ;;
    *)
      subcommand="$argument"
      break
      ;;
  esac
done

case "$subcommand" in
  fetch|pull|push|clone|ls-remote) ;;
  *) exec "$real" "$@" ;;
esac

if [ -z "\${${LEASE_VARIABLE}:-}" ]; then
  "$real" "$@"
  status=$?
  if [ "$status" -ne 0 ]; then
    echo "git $subcommand: if this needed GitHub, ${NO_CREDENTIAL}" >&2
  fi
  exit "$status"
fi

header=$(printf 'x-access-token:%s' "$${LEASE_VARIABLE}" | base64 | tr -d '\\n')
GIT_TERMINAL_PROMPT=0 "$real" -c "http.https://github.com/.extraheader=Authorization: Basic $header" "$@"
status=$?
if [ "$status" -ne 0 ] && [ "$subcommand" = push ]; then
  if [ "\${${ROLE_VARIABLE}:-}" = implementer ]; then
    echo "${PUSH_HINT}" >&2
  else
    echo "git push: ${NO_PUSH_HINT}" >&2
  fi
fi
exit "$status"
`;

/** Where the wrappers are installed: ahead of `/usr/bin` on `PATH`. */
export const SHIM_DIRECTORY = "/usr/local/bin";
